#!/usr/bin/env python3
"""Generate the 160x64, four-colour Atari title artwork and its packed bitmap data.

Pillow and the DejaVu Sans Bold font are needed only to regenerate the asset.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument('--preview', type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
im = Image.new('P', (160, 64), 0)
d = ImageDraw.Draw(im)
font = ImageFont.truetype('/usr/share/fonts/TTF/DejaVuSans-Bold.ttf', 20)
# Sparse stars and an orbit communicate movement without flashing glyphs.
for x, y in ((3,8),(12,27),(7,54),(21,4),(30,61),(43,3),(119,5),
             (139,9),(154,29),(150,56),(136,61),(100,62),(61,62)):
    d.point((x,y), fill=1)
d.arc((0, 31, 43, 62), 205, 352, fill=1, width=1)
d.ellipse((6,39,18,51), outline=3, width=1)
d.arc((117, 5, 159, 37), 15, 171, fill=1, width=1)
d.ellipse((140,14,150,24), outline=3, width=1)
d.line((137,23,153,15), fill=1, width=1)
for word, y in [('BOUNCY', 3), ('WORLD', 29)]:
    box = d.textbbox((0,0), word, font=font, stroke_width=1)
    x = (160 - (box[2]-box[0])) // 2
    d.text((x+2,y+2), word, font=font, fill=3, stroke_width=1, stroke_fill=3)
    d.text((x,y), word, font=font, fill=2, stroke_width=1, stroke_fill=1)
d.line((47,58,113,58),fill=3)
raw = bytearray()
for y in range(64):
    for x in range(0,160,4):
        raw.append(sum(im.getpixel((x+i,y)) << (6-2*i) for i in range(4)))
out = root/'src/atari/title_bitmap.h'
lines = [', '.join(f'0x{v:02x}' for v in raw[i:i+16]) for i in range(0,len(raw),16)]
out.write_text('/* Generated by scripts/generate_atari_title.py; do not edit. */\n'
               'static unsigned char title_bitmap[] = {\n    '
               + ',\n    '.join(lines) + '\n};\n')
im.putpalette([0,0,0, 70,160,220, 255,255,255, 255,155,25] + [0,0,0]*252)
if args.preview:
    im.convert('RGB').resize((640,256), Image.Resampling.NEAREST).save(args.preview)
print(f'{len(raw)} bitmap bytes')
